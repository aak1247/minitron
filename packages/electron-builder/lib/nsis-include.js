"use strict";

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const tempDirectories = new Set();
const SYSTEM_INCLUDE_NAMES = new Set([
  "filefunc.nsh",
  "logiclib.nsh",
  "mui.nsh",
  "mui2.nsh",
  "nsdialogs.nsh",
  "winver.nsh",
  "x64.nsh",
  "wordfunc.nsh",
  "textfunc.nsh",
  "sections.nsh",
  "installoptions.nsh",
  "envvarupdate.nsh",
  "inetc.nsh",
  "nsisdl.nsh",
  "startmenu.nsh",
]);
const USER_HOOK_ALIASES = new Map([
  ["customuninit", "minitronUserUnInit"],
  ["customcheckapprunning", "minitronUserCheckAppRunning"],
]);
const USER_HOOK_DISPLAY_NAMES = new Map([
  ["customuninit", "customUnInit"],
  ["customcheckapprunning", "customCheckAppRunning"],
]);

function composeInstallerInclude({ userIncludes, lifecycleIncludePath, projectDir }) {
  const lifecyclePath = path.resolve(lifecycleIncludePath);
  assertFile(lifecyclePath, "Minitron installer lifecycle include");
  const includes = normalizeIncludes(userIncludes).map((includePath) => resolveUserInclude(includePath, projectDir));
  if (includes.length === 0) return lifecyclePath;

  const graph = inspectIncludeGraph(includes, projectDir);
  if (graph.userAliasDefinitions.length > 0) {
    throw new Error(`NSIS include already defines reserved Minitron user hook macro: ${graph.userAliasDefinitions[0]}`);
  }
  for (const [name, definitions] of Object.entries(graph.userHookDefinitions)) {
    if (definitions.length > 1) {
      throw new Error(`NSIS includes define ${USER_HOOK_DISPLAY_NAMES.get(name)} more than once (${definitions.map((entry) => entry.path).join(", ")}); refusing to drop or merge hooks silently`);
    }
  }

  const outputDir = fs.mkdtempSync(path.join(os.tmpdir(), "minitron-nsis-"));
  tempDirectories.add(outputDir);
  const wrapperPath = path.join(outputDir, "minitron-includes.nsh");
  const activeHooks = new Set(Object.entries(graph.userHookDefinitions)
    .filter(([, definitions]) => definitions.length === 1)
    .map(([name]) => name.toLowerCase()));
  const transformed = activeHooks.size > 0 ? copyAndRewriteGraph(graph.files, graph.includeTargets, outputDir, activeHooks) : new Map();
  const wrapperIncludes = includes.map((includePath) => transformed.get(realPath(includePath)) || includePath);
  const lines = ["; Generated by @minitron/electron-builder."];
  for (const includePath of wrapperIncludes) lines.push(`!include ${quoteNsis(includePath)}`);
  lines.push(`!include ${quoteNsis(lifecyclePath)}`, "");
  fs.writeFileSync(wrapperPath, lines.join("\r\n"), { encoding: "utf8", flag: "wx" });
  return wrapperPath;
}

function normalizeIncludes(value) {
  if (value == null) return [];
  const values = Array.isArray(value) ? value : [value];
  return values.map((includePath, index) => {
    if (typeof includePath !== "string" || includePath.trim() === "") {
      throw new TypeError(`config.nsis.include[${index}] must be a non-empty path`);
    }
    return includePath;
  });
}

function resolveUserInclude(includePath, projectDir) {
  const resolved = path.isAbsolute(includePath) ? path.normalize(includePath) : path.resolve(projectDir, includePath);
  assertFile(resolved, `electron-builder NSIS include ${includePath}`);
  return resolved;
}

function inspectIncludeGraph(rootIncludes, projectDir) {
  const files = new Map();
  const includeTargets = new Map();
  const userHookDefinitions = Object.fromEntries([...USER_HOOK_ALIASES.keys()].map((name) => [name, []]));
  const userAliasDefinitions = [];
  const searchDirs = [projectDir];

  function visit(filePath) {
    const canonicalPath = realPath(filePath);
    if (files.has(canonicalPath)) return;
    const content = fs.readFileSync(canonicalPath, "utf8");
    files.set(canonicalPath, content);
    const lines = content.split(/(?<=\n)/);
    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index];
      const addDir = parseAddIncludeDir(line);
      if (addDir) {
        const directory = resolveIncludeDirectory(addDir, path.dirname(canonicalPath), projectDir);
        if (directory && !searchDirs.includes(directory)) searchDirs.push(directory);
      }
      const macro = parseMacroDirective(line);
      if (macro && macro.kind === "macro") {
        const lowerName = macro.name.toLowerCase();
        if (userHookDefinitions[lowerName]) {
          userHookDefinitions[lowerName].push({ path: canonicalPath, line: index + 1 });
        }
        if ([...USER_HOOK_ALIASES.values()].some((alias) => alias.toLowerCase() === lowerName)) {
          userAliasDefinitions.push(`${canonicalPath}:${index + 1}`);
        }
      }

      const include = parseInclude(line);
      if (!include) continue;
      if (SYSTEM_INCLUDE_NAMES.has(path.basename(include.value).toLowerCase())) continue;
      const nested = resolveNestedInclude(include.value, path.dirname(canonicalPath), projectDir, searchDirs);
      if (nested) {
        includeTargets.set(`${canonicalPath}:${index}`, realPath(nested));
        visit(nested);
      } else if (isDynamicInclude(include.value)) {
        throw new Error(`Cannot safely compose dynamic nested NSIS include at ${canonicalPath}:${index + 1}: ${include.value}`);
      } else if (!SYSTEM_INCLUDE_NAMES.has(path.basename(include.value).toLowerCase())) {
        throw new Error(`Cannot resolve nested NSIS include at ${canonicalPath}:${index + 1}: ${include.value}; add its directory with !addincludedir or use an absolute path`);
      }
    }
  }

  for (const includePath of rootIncludes) visit(includePath);
  return { files, includeTargets, userHookDefinitions, userAliasDefinitions };
}

function copyAndRewriteGraph(files, includeTargets, outputDir, activeHooks) {
  const destinations = new Map();
  let index = 0;
  for (const sourcePath of files.keys()) {
    const extension = path.extname(sourcePath) || ".nsh";
    destinations.set(sourcePath, path.join(outputDir, `user-${index++}${extension}`));
  }

  for (const [sourcePath, content] of files) {
    const destinationPath = destinations.get(sourcePath);
    const rewritten = content.split(/(?<=\n)/).map((line, lineIndex) => {
      let result = line;
      const macro = parseMacroDirective(result);
      if (macro && activeHooks.has(macro.name.toLowerCase())) {
        result = replaceMacroName(result, macro, USER_HOOK_ALIASES.get(macro.name.toLowerCase()));
      }
      const include = parseInclude(result);
      if (include) {
        const resolvedPath = includeTargets.get(`${sourcePath}:${lineIndex}`);
        if (resolvedPath && destinations.has(resolvedPath)) {
          result = result.slice(0, include.tokenStart) + quoteNsis(destinations.get(resolvedPath)) + result.slice(include.tokenEnd);
        }
      }
      return result;
    }).join("");
    fs.writeFileSync(destinationPath, rewritten, { encoding: "utf8", flag: "wx" });
  }
  return destinations;
}

function parseInclude(line) {
  const match = /^(\s*!\s*include\s+)(?:\/NONFATAL\s+)?("([^"]+)"|'([^']+)'|([^\s;]+))(.*)$/i.exec(stripLineEnding(line));
  if (!match) return undefined;
  const value = match[3] || match[4] || match[5];
  const tokenStart = match[0].indexOf(match[2]);
  return {
    value,
    tokenStart,
    tokenEnd: tokenStart + match[2].length,
  };
}

function parseAddIncludeDir(line) {
  const match = /^\s*!\s*addincludedir\s+(?:"([^"]+)"|'([^']+)'|([^\s;]+))/i.exec(stripLineEnding(line));
  return match ? match[1] || match[2] || match[3] : undefined;
}

function parseMacroDirective(line) {
  const match = /^\s*!\s*(macro|insertmacro|ifmacrodef|ifmacrondef|undefmacro)\s+(?:"([^"]+)"|'([^']+)'|([^\s;]+))/i.exec(line);
  if (!match) return undefined;
  return { kind: match[1].toLowerCase(), name: match[2] || match[3] || match[4], match };
}

function replaceMacroName(line, directive, replacement) {
  const match = directive.match;
  const name = directive.name;
  const offset = match[0].lastIndexOf(name);
  const start = match.index + offset;
  return `${line.slice(0, start)}${replacement}${line.slice(start + name.length)}`;
}

function resolveNestedInclude(value, currentDir, projectDir, searchDirs) {
  if (isDynamicInclude(value)) return undefined;
  const candidates = [];
  const windowsPath = value.replaceAll("\\", path.sep);
  if (path.isAbsolute(windowsPath)) candidates.push(windowsPath);
  else {
    candidates.push(path.resolve(currentDir, windowsPath), path.resolve(projectDir, windowsPath));
    for (const directory of searchDirs) candidates.push(path.resolve(directory, windowsPath));
  }
  const nsisDir = process.env.NSISDIR;
  if (nsisDir && !path.isAbsolute(windowsPath)) {
    candidates.push(path.resolve(nsisDir, "Include", windowsPath));
  }
  for (const candidate of candidates) {
    try {
      if (fs.statSync(candidate).isFile()) return candidate;
    } catch {
      // Try the next include search location.
    }
  }
  return undefined;
}

function resolveIncludeDirectory(value, currentDir, projectDir) {
  if (isDynamicInclude(value)) {
    throw new Error(`Cannot safely resolve dynamic !addincludedir path ${value}`);
  }
  const normalized = value.replaceAll("\\", path.sep);
  return path.resolve(path.isAbsolute(normalized) ? normalized : path.resolve(currentDir || projectDir, normalized));
}

function isDynamicInclude(value) {
  return /\$\{|\$[A-Za-z_]/.test(value);
}

function assertFile(filePath, label) {
  try {
    if (fs.statSync(filePath).isFile()) return;
  } catch {
    // Use the same actionable error for missing and non-file paths.
  }
  throw new Error(`${label} is missing or is not a file: ${filePath}`);
}

function realPath(filePath) {
  return fs.realpathSync.native ? fs.realpathSync.native(filePath) : fs.realpathSync(filePath);
}

function quoteNsis(value) {
  if (value.includes('"')) throw new Error(`NSIS include path contains an unsupported quote: ${value}`);
  return `"${value}"`;
}

function stripLineEnding(value) {
  return value.replace(/[\r\n]+$/, "");
}

function cleanup() {
  for (const directory of tempDirectories) {
    try {
      fs.rmSync(directory, { recursive: true, force: true });
    } catch {
      // The build output already contains only the composed include paths.
    }
  }
  tempDirectories.clear();
}

process.once("exit", cleanup);

module.exports = { composeInstallerInclude, inspectIncludeGraph };
